/**
 * The two files the app loads the catalogue through, generated from the courses: SUMMARIES_FILE,
 * every course's `ProblemSummary` (what the problem list, scores, badges and timed runs read), and
 * MODULES_FILE, the module each course is fetched from, as a chunk of its own, when it opens.
 * `yarn build:summaries` writes them; `yarn verify` renders them again and fails when the committed
 * files differ.
 */
import {execFileSync} from 'node:child_process';
import {existsSync, readdirSync} from 'node:fs';
import {join, resolve} from 'node:path';

import * as companies from '../src/data/companies';
import type {Company, Problem, ProblemSummary, StepSummary} from '../src/lib/types';

const PROBLEMS_DIR = 'src/data/problems';
export const SUMMARIES_FILE = `${PROBLEMS_DIR}/summaries.ts`;
export const MODULES_FILE = `${PROBLEMS_DIR}/modules.ts`;

/** Every field a summary keeps, once: a field added to `ProblemSummary` and missing here does not compile. */
const SUMMARY_FIELDS = {
  id: true,
  title: true,
  tagline: true,
  difficulty: true,
  concepts: true,
  minutes: true,
  track: true,
  tag: true,
  language: true,
  company: true,
  steps: true,
} satisfies Record<keyof ProblemSummary, true>;

const STEP_FIELDS = {id: true, title: true, concept: true} satisfies Record<keyof StepSummary, true>;

const HEADER =
  '// Generated by `yarn build:summaries` from the courses in src/data/problems/index.ts. DO NOT EDIT.\n\n';

const isProblem = (value: unknown): value is Problem =>
  typeof value === 'object' && value !== null && 'steps' in value && 'statement' in value;

/** A value as TypeScript source: bare object keys where they can be, `undefined` fields left out. */
const literal = (value: unknown): string => {
  if (Array.isArray(value)) return `[${value.map(literal).join(', ')}]`;
  if (typeof value !== 'object' || value === null) return JSON.stringify(value);
  const fields = Object.entries(value).filter(([, v]) => v !== undefined);
  return `{${fields
    .map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k)}: ${literal(v)}`)
    .join(', ')}}`;
};

/** The constant of src/data/companies.ts a course's company is. */
const companyName = (company: Company): string => {
  const name = Object.entries(companies).find(([, value]) => value === company)?.[0];
  if (name === undefined) throw new Error(`company '${company.id}' is not exported from src/data/companies.ts`);
  return name;
};

const summarySource = (problem: Problem): string => {
  const fields = (Object.keys(SUMMARY_FIELDS) as (keyof ProblemSummary)[]).flatMap(key => {
    if (problem[key] === undefined) return [];
    if (key === 'company' && problem.company !== undefined) return [`company: ${companyName(problem.company)}`];
    if (key === 'steps') {
      const keys = Object.keys(STEP_FIELDS) as (keyof StepSummary)[];
      return [`steps: ${literal(problem.steps.map(step => Object.fromEntries(keys.map(k => [k, step[k]]))))}`];
    }
    return [`${key}: ${literal(problem[key])}`];
  });
  return `{${fields.join(', ')}}`;
};

/** The repo's prettier, so the generated files pass `yarn lint` like the rest of src/. */
const format = (file: string, source: string): string =>
  execFileSync(resolve('node_modules/.bin/prettier'), ['--stdin-filepath', file], {input: source, encoding: 'utf8'});

/** Both files as the courses render them: path → source. */
export async function renderSummaries(): Promise<Record<string, string>> {
  // Lazy, like verify's own import of the index: verify imports this module, and `--file` must not
  // load every course.
  const {problems} = await import('../src/data/problems');
  // Where each course is exported from: its directory's index.ts (found by listing the directories,
  // so imported by a computed path), under its own name.
  const modules = new Map<string, {path: string; name: string}>();
  for (const dir of readdirSync(PROBLEMS_DIR).sort()) {
    const path = join(PROBLEMS_DIR, dir, 'index.ts');
    if (!existsSync(path)) continue;
    const exports = (await import(resolve(path))) as Record<string, unknown>;
    for (const [name, value] of Object.entries(exports)) {
      if (isProblem(value)) modules.set(value.id, {path: `./${dir}/index`, name});
    }
  }
  const tagged = [...new Set(problems.flatMap(p => (p.company === undefined ? [] : [companyName(p.company)])))].sort();
  const summaries =
    HEADER +
    (tagged.length === 0 ? '' : `import {${tagged.join(', ')}} from '@/data/companies';\n`) +
    "import type {ProblemSummary} from '@/lib/types';\n\n" +
    '/** Every course as the problem list knows it, in catalogue order; the course itself loads when it opens. */\n' +
    `export const problemSummaries: readonly ProblemSummary[] = [${problems.map(summarySource).join(', ')}];\n`;
  const loaders = problems.map(problem => {
    const source = modules.get(problem.id);
    if (source === undefined) throw new Error(`${problem.id}: no src/data/problems/*/index.ts exports it`);
    return `${JSON.stringify(problem.id)}: () => import('${source.path}').then(m => m.${source.name})`;
  });
  const moduleMap =
    HEADER +
    "import type {Problem} from '@/lib/types';\n\n" +
    '/** Each course by id: its module, a chunk of its own, fetched the first time the course opens (see load.ts). */\n' +
    `export const problemModules: Partial<Record<string, () => Promise<Problem>>> = {${loaders.join(', ')}};\n`;
  return {[SUMMARIES_FILE]: format(SUMMARIES_FILE, summaries), [MODULES_FILE]: format(MODULES_FILE, moduleMap)};
}
